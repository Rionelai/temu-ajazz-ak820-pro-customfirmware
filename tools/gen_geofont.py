"""Georgian (Mkhedruli) bitmap font for the AK820 Pro screen (U8, firmware/u8/u8app.c).

Renders the 33 Mkhedruli letters (U+10D0..U+10F0) from Noto Sans Georgian and digits / a few
signs from Noto Sans (both SIL Open Font License 1.1, https://github.com/notofonts) into 1-bit glyphs,
16 rows high, and writes firmware/u8/geofont.h. Also writes a preview PNG.

  python tools/gen_geofont.py NotoSansGeorgian-Bold.ttf NotoSans-Bold.ttf [size]
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

ROWS = 16
CHARS = [chr(c) for c in range(0x10D0, 0x10F1)] + list('0123456789%: ')

def main():
    size = int(sys.argv[3]) if len(sys.argv) > 3 else 13
    geo = ImageFont.truetype(sys.argv[1], size)
    lat = ImageFont.truetype(sys.argv[2], size)
    base = 12                                    # baseline row inside the 16-row cell
    glyphs = []
    for ch in CHARS:
        if ch == ' ':
            glyphs.append((ch, 4, [0] * ROWS)); continue
        font = geo if ord(ch) >= 0x10D0 else lat
        img = Image.new('L', (32, 40), 0)
        ImageDraw.Draw(img).text((2, base + 8), ch, font=font, fill=255, anchor='ls')   # baseline at y = base + 8
        px = img.load()
        cols = [x for x in range(32) if any(px[x, y] >= 128 for y in range(40))]
        if not cols:
            sys.exit(f'glyph {ch!r} ({ord(ch):04X}) not in the font')
        x0, x1 = cols[0], cols[-1]
        w = x1 - x0 + 1
        assert w <= 16, (ch, w)
        rows = []
        for r in range(ROWS):
            y = r + 8                               # cell row r = image row r + 8
            bits = 0
            for x in range(w):
                if px[x0 + x, y] >= 128: bits |= 1 << (15 - x)
            rows.append(bits)
        lost = sum(1 for y in list(range(0, 8)) + list(range(ROWS + 8, 40)) for x in range(32) if px[x, y] >= 128)
        assert lost == 0, f'glyph {ch!r} does not fit the 16-row cell ({lost} px outside)'
        glyphs.append((ch, w, rows))

    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, '..', 'firmware', 'u8', 'geofont.h')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/gen_geofont.py from Noto Sans Georgian Bold (SIL OFL 1.1,\n')
        f.write('// Copyright 2022 The Noto Project Authors, https://github.com/notofonts/georgian).\n')
        f.write(f'// {len(glyphs)} glyphs, {ROWS} rows each (baseline = row {base}), MSB = leftmost pixel.\n')
        f.write('#pragma once\n#include <stdint.h>\n')
        f.write('// code point (Mkhedruli: U+10D0..U+10F0, else ASCII), width, 16 rows\n')
        f.write('typedef struct { uint16_t cp; uint8_t w; uint16_t row[16]; } geo_glyph_t;\n')
        f.write(f'static const geo_glyph_t GEO[{len(glyphs)}] = {{\n')
        for ch, w, rows in glyphs:
            f.write(f'    {{0x{ord(ch):04X}, {w:2d}, {{' + ', '.join(f'0x{r:04X}' for r in rows) + '}},\n')
        f.write('};\n')

    # preview: all glyphs side by side, 3x
    W = sum(w + 1 for _, w, _ in glyphs)
    im = Image.new('RGB', (W * 3, ROWS * 3), (20, 20, 18))
    x = 0
    for ch, w, rows in glyphs:
        for r in range(ROWS):
            for c in range(w):
                if rows[r] >> (15 - c) & 1:
                    for dy in range(3):
                        for dx in range(3): im.putpixel(((x + c) * 3 + dx, r * 3 + dy), (217, 119, 87))
        x += w + 1
    prev = os.path.join(os.environ.get('TEMP', here), 'geofont_preview.png')
    im.save(prev)
    print(f'wrote {out} ({len(glyphs)} glyphs), preview {prev}')

if __name__ == '__main__':
    main()

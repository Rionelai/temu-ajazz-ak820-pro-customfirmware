"""Turn the guided key mapping (keymap.csv: key,pair  e.g. "Esc,a7-a13") into
firmware/keyboard/keymap.h for the replacement firmware.

usage:  python tools/gen_keymap.py [keymap.csv] [firmware/keyboard/keymap.h]
Pin names come from the key finder: aN = PAN, bN = PBN (index 16+N in the firmware).
"""
import csv, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'keymap.csv')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', 'firmware', 'keyboard', 'keymap.h')

# USB HID keyboard usages (HID Usage Tables, page 0x07). K_FN / K_KNOB are firmware-internal.
HID = {
    'Esc': 0x29, 'F1': 0x3A, 'F2': 0x3B, 'F3': 0x3C, 'F4': 0x3D, 'F5': 0x3E, 'F6': 0x3F,
    'F7': 0x40, 'F8': 0x41, 'F9': 0x42, 'F10': 0x43, 'F11': 0x44, 'F12': 0x45, 'Delete': 0x4C,
    'Grave': 0x35, '1': 0x1E, '2': 0x1F, '3': 0x20, '4': 0x21, '5': 0x22, '6': 0x23, '7': 0x24,
    '8': 0x25, '9': 0x26, '0': 0x27, 'Minus': 0x2D, 'Equal': 0x2E, 'Backspace': 0x2A, 'Home': 0x4A,
    'Tab': 0x2B, 'LBracket': 0x2F, 'RBracket': 0x30, 'Backslash': 0x31, 'PgUp': 0x4B,
    'CapsLock': 0x39, 'Semicolon': 0x33, 'Quote': 0x34, 'Enter': 0x28, 'PgDn': 0x4E,
    'LShift': 0xE1, 'Comma': 0x36, 'Period': 0x37, 'Slash': 0x38, 'RShift': 0xE5, 'Up': 0x52,
    'LCtrl': 0xE0, 'Win': 0xE3, 'LAlt': 0xE2, 'Space': 0x2C, 'RAlt': 0xE6, 'RCtrl': 0xE4,
    'Left': 0x50, 'Down': 0x51, 'Right': 0x4F, 'End': 0x4D,
    'Fn': 'K_FN', 'KnobPress': 'K_KNOB',
}
for i, c in enumerate('ABCDEFGHIJKLMNOPQRSTUVWXYZ'):
    HID[c] = 0x04 + i

# Fn layer (Fn held). Fn+arrows / \ / - / = / X are the lighting combos (firmware/keyboard/rgb.c),
# as on the original Ajazz firmware, so they get no key code here.
FN = {'Delete': 0x49, 'Backspace': 0x4C}                       # Insert, Delete


def pin_index(name):
    port, num = name[0], int(name[1:])
    if port == 'a' and 0 <= num < 16:
        return num
    if port == 'b' and 0 <= num < 24:
        return 16 + num
    raise ValueError(f'bad pin name {name!r}')


rows = []
with open(src, newline='') as f:
    for r in csv.DictReader(f):
        key, pair = r['key'].strip(), r['pair'].strip()
        if not pair:
            continue
        if key not in HID:
            sys.exit(f'unknown key name {key!r} in {src}')
        x, y = (pin_index(p) for p in pair.split('-'))
        rows.append((key, x, y, HID[key], FN.get(key, 0)))

seen = {}
for key, x, y, *_ in rows:
    if (x, y) in seen:
        sys.exit(f'pin pair {x}-{y} used by both {seen[(x, y)]} and {key}: re-map one of them')
    seen[(x, y)] = key

fmt = lambda v: v if isinstance(v, str) else f'0x{v:02X}'
with open(dst, 'w', newline='\n') as f:
    f.write('// Generated by tools/gen_keymap.py from keymap.csv - do not edit by hand.\n')
    f.write('#pragma once\n#include <stdint.h>\n\n')
    f.write('#define K_FN   0xF0  /* Fn layer key (internal) */\n')
    f.write('#define K_KNOB 0xF1  /* knob press = mute (internal) */\n')
    # 1 on SG-8975US Ver:02: with 0, turning the knob right lowered the volume
    f.write('#ifndef KNOB_INVERT\n#define KNOB_INVERT 1  /* flip if volume goes the wrong way */\n#endif\n\n')
    f.write('typedef struct { uint8_t x, y, code, fn_code; } key_t;\n')
    f.write(f'#define NKEYS {len(rows)}\n')
    f.write('static const key_t KEYS[NKEYS] = {\n')
    for key, x, y, code, fn in rows:
        f.write(f'    {{{x:2d}, {y:2d}, {fmt(code)}, {fmt(fn)}}},  /* {key} */\n')
    f.write('};\n')
print(f'{len(rows)} keys -> {dst}')
missing = [k for k in HID if k not in {r[0] for r in rows} and len(k) > 0 and k != 'End']
if missing:
    print('not mapped yet:', ', '.join(missing))
